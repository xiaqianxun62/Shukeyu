-- ============================================================
-- 赛事轮次自定义
--
-- 原来轮次是「副产物」：小组赛轮数由每组队数决定（单循环 k-1 轮），
-- 淘汰赛轮数由晋级人数决定（2 的幂）。现在两者都可以由管理员直接指定。
--
--   group_rounds    小组赛轮数
--                   0 = 自动（按每组队数打满单循环：偶数队 k-1 轮、奇数队 k 轮）
--                   > 0 = 指定轮数；小于满轮即部分循环，大于满轮即多循环
--                        （双循环及以上，每遍主客互换）
--
--   knockout_rounds 淘汰赛轮数（不含季军赛 / 决赛）
--                   0 = 自动（按晋级人数推导，规模向上取 2 的幂）
--                   > 0 = 指定轮数，对应规模 2^(轮数+1)；晋级人数超出时自动扩容
--                        到能容纳的规模，容纳不下时首轮出现轮空
-- ============================================================

ALTER TABLE `tournament`
  ADD COLUMN `group_rounds` INT NOT NULL DEFAULT 0
    COMMENT '小组赛轮数：0=自动（打满单循环）；>0=指定轮数（超过满轮即多循环）',
  ADD COLUMN `knockout_rounds` INT NOT NULL DEFAULT 0
    COMMENT '淘汰赛轮数（不含季军赛/决赛）：0=自动（按晋级人数推导）；>0=指定轮数，规模=2^(轮数+1)';
